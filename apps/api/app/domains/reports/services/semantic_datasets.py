def _reference_dataset(
    *,
    dataset_id: str,
    name: str,
    source_ref: str,
    description: str,
) -> SemanticDatasetDefinition:
    return _definition(
        dataset_id=dataset_id,
        name=name,
        description=description,
        owning_domain="reference_data",
        source_kind="reference_data",
        source_ref=source_ref,
        grain="one row per reference record",
        default_sort=["code"],
        freshness_policy="live_reference_data",
        fields=[
            _field("code", "Code", "string", "identifier"),
            _field("name", "Name", "string", "dimension"),
            _field("description", "Description", "string", "narrative", nullable=True, groupable=False),
            _field("is_active", "Active", "boolean", "status"),
            _field("updated_at", "Updated At", "datetime", "timestamp"),
            _field("version", "Version", "integer", "measure", aggregatable=False),
        ],
    )


def list_semantic_dataset_definitions() -> list[SemanticDatasetDefinition]:
    return sorted(_dataset_definitions_by_id().values(), key=lambda definition: definition.dataset_id)


def get_semantic_dataset_definition(dataset_id: str) -> SemanticDatasetDefinition | None:
    return _dataset_definitions_by_id().get(dataset_id)
