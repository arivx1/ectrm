from apps.api.app.schemas.report import SemanticDatasetDefinition, SemanticDatasetField


def _field(
    field_key: str,
    label: str,
    data_type: str,
    role: str,
    *,
    nullable: bool = False,
    filterable: bool = True,
    groupable: bool = True,
    aggregatable: bool = False,
    formula_eligible: bool = True,
    description: str | None = None,
    source_path: str | None = None,
) -> dict[str, object]:
    return {
        "field_key": field_key,
        "label": label,
        "data_type": data_type,
        "role": role,
        "nullable": nullable,
        "filterable": filterable,
        "groupable": groupable,
        "aggregatable": aggregatable,
        "formula_eligible": formula_eligible,
        "description": description,
        "source_path": source_path or field_key,
    }


def _definition(
    *,
    dataset_id: str,
    name: str,
    description: str,
    owning_domain: str,
    source_kind: str,
    source_ref: str,
    grain: str,
    fields: list[dict[str, object]],
    parameter_keys: list[str] | None = None,
    default_sort: list[str] | None = None,
    freshness_policy: str = "live_projection",
    access_policy_key: str = "reports.read",
) -> SemanticDatasetDefinition:
    return SemanticDatasetDefinition(
        dataset_id=dataset_id,
        name=name,
        description=description,
        owning_domain=owning_domain,
        source_kind=source_kind,
        source_ref=source_ref,
        grain=grain,
        fields=[SemanticDatasetField.model_validate(field) for field in fields],
        parameter_keys=parameter_keys or [],
        default_sort=default_sort or [],
        freshness_policy=freshness_policy,
        access_policy_key=access_policy_key,
    )


